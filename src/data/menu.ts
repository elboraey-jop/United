export type MenuItem = {
  id: string;
  name: string;
  category: CategoryId;
  group: string;
  note?: string;
  sizes: CupSize[];
  options?: string[];
  optionLabel?: string;
  signature?: boolean;
};

export type CategoryId =
  | "coffee"
  | "tea"
  | "cocoa"
  | "cold"

const items: MenuItem[] = [];
let seq = 0;

function add(
  category: CategoryId,
  group: string,
  name: string,
  sizes: CupSize[],
  extra: Partial<Omit<MenuItem, "id" | "category" | "group" | "name" | "sizes">> = {},
) {
  items.push({ id: `${category}-${++seq}`, category, group, name, sizes, ...extra });
}

